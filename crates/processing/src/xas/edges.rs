pub fn edge_energy(element: &str, edge: &str) -> Option<f64> {
    EDGES
        .iter()
        .find(|row| row.0.eq_ignore_ascii_case(element) && row.1.eq_ignore_ascii_case(edge))
        .map(|row| row.2)
}

/// The K or L3 edge closest to `energy`. L1 and L2 are rarely measured and sit
/// between those edges, where a chemically shifted E0 would land on them.
pub fn nearest_edge(energy: f64) -> Option<(&'static str, &'static str, f64)> {
    EDGES
        .iter()
        .copied()
        .filter(|row| matches!(row.1, "K" | "L3"))
        .min_by(|left, right| (left.2 - energy).abs().total_cmp(&(right.2 - energy).abs()))
}
